import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=file=>JSON.parse(fs.readFileSync(path.join(root,file),'utf8'));
const historical=read('sources/codex-secondary-consensus.en.json'),pack=read('content/chaos-space-marines-faction-pack.en.json'),related=read('content/chaos-space-marines-related-rules.en.json'),points=read('content/chaos-space-marines-points.en.json'),codex=read('content/chaos-space-marines-codex-datasheets.en.json'),manifest=read('sources/source-manifest.json'),corpus=read('sources/waha-11e-current-2026-09-29/corpus.json');

assert.equal(historical.records.length,91,'historical secondary census denominator changed');
assert.equal(historical.summary.byStatus['SECONDARY CONSENSUS'],89);
assert.equal(historical.summary.byStatus['SOURCE MISSING'],2);
assert.deepEqual(historical.records.filter(record=>record.status==='SOURCE MISSING').map(record=>record.id),['detachment-rule-body-deceptors-masters-of-misdirection','datasheet-ability-options-abaddon-the-despoiler-warmaster']);
assert.equal(manifest.secondaryConsensus.status,'historical-adjudicated-secondary-consensus');
assert.deepEqual([manifest.secondaryConsensus.evaluated,manifest.secondaryConsensus.imported,manifest.secondaryConsensus.sourceMissing,manifest.secondaryConsensus.conflicts,manifest.secondaryConsensus.guessed],[91,91,0,0,0]);
assert.equal(manifest.gates.publishAsComplete,true);
assert.deepEqual(manifest.knownGaps,[]);
assert.equal(manifest.enrollmentScope.currentNonLegendsDatasheets,54);
assert.equal(corpus.gameplayUnits,3998);
assert.equal(corpus.datasheets.length,54);
assert.equal(pack.detachments.length,17);
assert.equal(pack.detachments.reduce((count,detachment)=>count+detachment.stratagems.length,0),93);
assert.equal(pack.detachments.reduce((count,detachment)=>count+detachment.enhancements.length,0),62);
assert.equal(pack.detachments.flatMap(detachment=>detachment.enhancements).filter(item=>!item.text?.trim()).length,0);
assert.equal(Object.keys(related.stratagems).length,93);
assert.equal(Object.keys(related.enhancements).length,62);
assert.equal(points.enhancements.length,62);
assert.equal(codex.datasheets.length,54);
const deceptors=pack.detachments.find(item=>item.id==='deceptors');
const warmaster=codex.datasheets.find(item=>item.id==='unit-abaddon-the-despoiler').abilities.find(item=>item.title==='The Warmaster');
assert.ok(deceptors.rule.text.trim());
assert.equal(deceptors.rule.provenance.status,'ACCEPTED_CURRENT_WAHA');
assert.equal(warmaster.choices.length,3);
assert.match(warmaster.provenance.sourceId,/waha-11e-current-2026-09-29/);
const duplicate=pack.detachments.flatMap(detachment=>detachment.enhancements.map(item=>({detachment:detachment.title,...item}))).filter(item=>item.title.toLowerCase()==='warp-fuelled thrusters');
assert.equal(duplicate.length,2);
assert.equal(new Set(duplicate.map(item=>item.id)).size,2,'duplicate title remains Detachment-qualified');

console.log('Chaos Space Marines source adjudication QA PASS: historical 91-record census retained; both former gaps closed by the accepted current Waha corpus; 0 active source gaps.');
