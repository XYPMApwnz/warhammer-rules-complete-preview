import assert from 'node:assert/strict';
import {applyOverlays,sourceCurrentness,validateRegistry} from './overlay-engine.mjs';

const waha = {id:'base',type:'WAHA_CAPTURE',versionOrDate:'2026-09-25',authority:'ACCEPTED_WAHA',effectiveFrom:'2026-09-25',status:'CURRENT',provenance:{capture:'pinned'}};
const gw = {id:'update',type:'OFFICIAL_PDF',versionOrDate:'v1.3',authority:'OFFICIAL_GW',effectiveFrom:'2026-09-30',status:'CURRENT',reconciled:true,provenance:{document:'pinned'}};
const base = {entities:[{id:'weapon-1',kind:'WEAPON',data:{strength:'4',keywords:['FRAME'],text:'base'},provenance:{sourceId:'base'}}]};
const replace = {id:'change',sourceId:'update',targetId:'weapon-1',field:['strength'],operation:'REPLACE',value:'5',effectiveFrom:gw.effectiveFrom,provenance:{page:7}};
const effective = applyOverlays(base,[waha,gw],[replace]);
assert.equal(base.entities[0].data.strength,'4','Never mutate historical base');
assert.equal(effective.entities[0].data.strength,'5');
assert.equal(effective.entities[0].data.text,'base','Unchanged fact passes through');
assert.equal(effective.entities[0].fieldProvenance.strength.sourceId,'update');
assert.deepEqual(effective,applyOverlays(base,[waha,gw],[replace]),'Deterministic build');
let mutations = 0;
const kill = action => {assert.throws(action);mutations++;};
kill(() => applyOverlays(base,[waha,gw],[{...replace,targetId:'missing'}]));
kill(() => applyOverlays(base,[waha,gw],[replace,{...replace,id:'conflict',value:'6'}]));
const nestedBase = {entities:[{id:'weapon-1',data:{profile:{strength:'4'}}}]};
const parentChange = {...replace,id:'a-parent',field:['profile'],value:{strength:'5'}};
const childChange = {...replace,id:'b-child',field:['profile','strength'],value:'6'};
kill(() => applyOverlays(nestedBase,[waha,gw],[parentChange,childChange]));
kill(() => applyOverlays(base,[waha,gw],[{...replace,field:['missing','strength']}]));
kill(() => applyOverlays(base,[waha,gw],[{...replace,operation:'ADD'}]));
kill(() => applyOverlays(base,[waha,gw],[{...replace,expectedBefore:'3'}]));
kill(() => applyOverlays(base,[waha,gw],[{...replace,field:['__proto__','polluted']}]));
kill(() => validateRegistry([waha,gw,gw]));
kill(() => applyOverlays(base,[waha,gw],[{...replace,sourceId:'base'}]));
assert.notEqual(applyOverlays(base,[waha,gw],[]).entities[0].data.strength,effective.entities[0].data.strength,'Removing overlay changes effective value');mutations++;
assert.equal(sourceCurrentness([waha,gw]).currentness,'CURRENT');
const newer = {...gw,id:'newer',effectiveFrom:'2026-10-01',reconciled:false};
assert.equal(sourceCurrentness([waha,gw,newer]).currentness,'STALE');mutations++;
assert.equal(sourceCurrentness([waha,gw],{blockingItems:['missing source evidence']}).currentness,'BLOCKED');
const superseded = {...gw,status:'SUPERSEDED'}, replacement = {...newer,reconciled:true,supersedes:['update']};
assert.equal(applyOverlays(base,[waha,superseded,replacement],[replace,{...replace,id:'later',sourceId:'newer',effectiveFrom:'2026-10-01',value:'6'}]).entities[0].data.strength,'6','Explicit precedence');
const add = {...replace,id:'add-frame',operation:'ADD',field:['keywords'],value:'FRAME'};
assert.deepEqual(applyOverlays(base,[waha,gw],[add]).entities[0].data.keywords,['FRAME'],'Official repeated keyword remains one fact');
const qualification = {...replace,id:'qualify',operation:'QUALIFY',field:['text'],value:{rangeCap:12}};
assert.deepEqual(applyOverlays(base,[waha,gw],[qualification]).entities[0].qualifications[0].value,{rangeCap:12});
const remove = {...replace,id:'remove',operation:'REMOVE',field:['text']};
assert.equal(Object.hasOwn(applyOverlays(base,[waha,gw],[remove]).entities[0].data,'text'),false);
console.log(`V2 overlay QA PASS: identity, provenance, ADD/REPLACE/REMOVE/QUALIFY, precedence, determinism, currentness; mutations=${mutations}`);
