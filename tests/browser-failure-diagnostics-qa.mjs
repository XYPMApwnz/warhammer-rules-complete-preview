import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {EventEmitter} from 'node:events';
import {createQaEvidenceDir} from './helpers/qa-temp.mjs';
import {createBrowserFailureDiagnostics} from './helpers/browser-failure-diagnostics.mjs';

const evidence=createQaEvidenceDir('browser-failure-diagnostics-');
const original=new Error('Negative control: original popup timeout');
const context=new EventEmitter(),page=new EventEmitter();
const frame={url:()=> 'http://test/v2/app.html',name:()=>'',content:async()=>'<html><body>Popup not ready</body></html>',evaluate:async()=>({readyState:'complete',appPresent:true})};
Object.assign(page,{url:()=>frame.url(),isClosed:()=>false,frames:()=>[frame]});
context.pages=()=>[];
const diagnostics=createBrowserFailureDiagnostics();diagnostics.observe(context,'390px');
assert.deepEqual(await fs.readdir(evidence),[],'Success-path observation must not create failure files');
context.emit('page',page);
page.emit('console',{type:()=> 'error',text:()=> 'Negative control console',location:()=>({url:frame.url(),lineNumber:3,columnNumber:0})});
page.emit('pageerror',new Error('Negative control page error'));
const pending={url:()=> 'http://test/pending.mjs',method:()=> 'GET',resourceType:()=> 'script'};
page.emit('request',pending);
const complete={url:()=> 'http://test/complete.mjs',method:()=> 'GET',resourceType:()=> 'script'};
page.emit('request',complete);
page.emit('response',{request:()=>complete,url:()=>complete.url(),status:()=>200});
page.emit('requestfinished',complete);
const file=await diagnostics.write(path.join(evidence,'failure-diagnostics'),original);
const report=JSON.parse(await fs.readFile(file,'utf8'));
assert.equal(report.error.message,original.message);
assert.equal(report.error.stack,original.stack);
assert.equal(report.snapshots[0].url,frame.url());
assert.equal(await fs.readFile(path.join(path.dirname(file),report.snapshots[0].frames[0].file),'utf8'),'<html><body>Popup not ready</body></html>');
assert.deepEqual(report.pendingRequests.map(item=>item.url),[pending.url()]);
assert(report.events.some(item=>item.type==='console'&&item.text==='Negative control console'));
assert(report.events.some(item=>item.type==='pageerror'&&item.message==='Negative control page error'));
assert(report.events.some(item=>item.type==='response'&&item.status===200));
assert.deepEqual(report.captureErrors,[]);
// A failed DOM/state capture is evidence, not a replacement for the test error.
frame.content=async()=>{throw new Error('Negative control: closed frame');};
frame.evaluate=async()=>{throw new Error('Negative control: detached context');};
const partial=JSON.parse(await fs.readFile(await diagnostics.write(path.join(evidence,'partial'),original),'utf8'));
assert.equal(partial.error.stack,original.stack);
assert.equal(partial.captureErrors.length,2);
assert.equal(partial.pendingRequests[0].url,pending.url());
console.log(JSON.stringify({status:'PASS',checks:13,evidence}));
