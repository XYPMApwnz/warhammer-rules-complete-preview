import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createBrowserPhases} from './helpers/browser-phases.mjs';
import {browserLaunchFailureDiagnostic} from './helpers/browser-launch.mjs';
import {createQaEvidenceDir} from './helpers/qa-temp.mjs';

const out=createQaEvidenceDir('browser-phase-controls-'),file=path.join(out,'PHASES.json');
const phases=createBrowserPhases(file);let calls=0;
assert.equal(await phases.run('frame-sync',()=>{calls++;return 17;},{book:'death-guard',width:390}),17);
assert.equal(calls,1,'A browser phase must not retry work');
assert.equal(phases.observations[0].status,'PASS');
const original=new Error('Private error body is retained only for the caller');
await assert.rejects(phases.run('snapshot',()=>Promise.reject(original)),error=>error===original);
assert.equal(phases.observations[1].status,'FAIL');
await assert.rejects(phases.run('boundary-ready',()=>new Promise(()=>{}),{ordinal:1},20),error=>error.code==='QA_BROWSER_PHASE_TIMEOUT');
assert.equal(phases.observations[2].status,'TIMEOUT');
assert(phases.observations[2].elapsedMs<1000,'A stalled browser callback is bounded by the Node timer');
await assert.rejects(phases.run('private arbitrary phase',()=>{},{}),/Unknown browser phase/);
await assert.rejects(phases.run('snapshot',()=>{},{path:'private path'}),/Unknown browser phase field/);
await assert.rejects(phases.run('snapshot',()=>{},{book:'private arbitrary book'}),/Unknown browser phase book/);
const report=JSON.parse(fs.readFileSync(file,'utf8'));
assert.equal(report.observations.length,3);
assert(!JSON.stringify(report).includes(original.message),'Private error text never enters phase metadata');
const bounded=createBrowserPhases();for(let index=0;index<150;index++)await bounded.run('snapshot',()=>{});
assert.equal(bounded.observations.length,128,'Phase history stays bounded');
assert.equal(bounded.totalCount,150);
assert.deepEqual(bounded.counts.snapshot,{started:150,passed:150,failed:0,timedOut:0,elapsedMs:bounded.counts.snapshot.elapsedMs});

const privateBody='PRIVATE_ERROR_BODY /runner/private/capture.html person@example.invalid secret=PRIVATE_KEY';
const diagnostic=(message,name='Error')=>browserLaunchFailureDiagnostic({name,message:message+' '+privateBody},{env:{TMPDIR:'/private/path'}});
assert.equal(diagnostic('Socket path too long').cause,'UNIX_SOCKET_PATH_TOO_LONG');
assert.equal(diagnostic('Failed to create a ProcessSingleton').cause,'PROFILE_SINGLETON_FAILURE');
assert.equal(diagnostic('error while loading shared libraries').cause,'SHARED_LIBRARY_UNAVAILABLE');
assert.equal(diagnostic('No usable sandbox').cause,'SANDBOX_UNAVAILABLE');
assert.equal(diagnostic('launch deadline','TimeoutError').cause,'LAUNCH_TIMEOUT');
assert.equal(diagnostic('unknown failure','PrivateErrorClass').errorClass,'Error');
const safe=JSON.stringify(diagnostic('unknown failure'));
assert.deepEqual(Object.keys(JSON.parse(safe)).sort(),['schema','phase','status','errorClass','cause','tempPathBytes'].sort());
assert(!/PRIVATE_ERROR_BODY|capture\.html|example\.invalid|PRIVATE_KEY|\/private\//.test(safe),'Launch metadata must never copy private message/path content');
assert.equal(JSON.parse(safe).tempPathBytes,13);
console.log(JSON.stringify({status:'PASS',checks:25}));
