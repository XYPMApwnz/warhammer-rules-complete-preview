"""Real CSM build and source controls; run with each supported QA Python."""
from pathlib import Path
import copy
import importlib.util
import json
import os
import sys
import tempfile
from unittest.mock import patch

from lxml import etree, html

ROOT = Path(__file__).resolve().parents[1]
HERE = ROOT / "books/chaos-space-marines/v2"
sys.path.insert(0, str(HERE))
spec = importlib.util.spec_from_file_location("parser_independent_csm_build", HERE / "build.py")
builder = importlib.util.module_from_spec(spec)
spec.loader.exec_module(builder)
from model_sources import _equal

checks = []


def rejects(name, action, message):
    try:
        action()
    except ValueError as error:
        assert message in str(error)
    else:
        raise AssertionError(name + " was accepted")
    checks.append(name)


def row(markup):
    return html.fromstring("<table>" + markup + "</table>").xpath(".//tr")[0]


first = row('<tr class="a" id="b"><td>One <b>two</b></td><td>3</td></tr>')
equivalent = row('<tr id="b" class="a"><td>One\n <b>two</b></td><td>3</td></tr>')
assert builder.row_text_fingerprint(first) == builder.row_text_fingerprint(equivalent)
checks.append("markup-serialization-and-whitespace-do-not-own-row-fingerprint")
assert builder.row_text_fingerprint(first) != builder.row_text_fingerprint(row('<tr><td>One two</td><td>4</td></tr>'))
assert builder.row_text_fingerprint(first) != builder.row_text_fingerprint(row('<tr><td>3</td><td>One two</td></tr>'))
checks.append("changed-cell-or-cell-order-changes-fingerprint")
rejects("non-row-rejected", lambda: builder.row_text_fingerprint(html.fromstring("<div>3</div>")), "not a table row")

binding = builder.read(HERE / "presentation-bindings.json")
document = builder.read(HERE / "presentation-row-text-fingerprints.json")
assert len(document["rows"]) == len(binding["instructionOccurrences"]) == 70
builder.row_text_expectations(document, binding["instructionOccurrences"])
for name, change, message in [
    ("missing-row-fails", lambda data: data["rows"].pop(), "inventory differs"),
    ("duplicate-row-fails", lambda data: data["rows"].append(copy.deepcopy(data["rows"][0])), "Identity collision"),
    ("invalid-digest-fails", lambda data: data["rows"][0].update(expectedRowTextSha256="not-a-hash"), "Invalid CSM"),
]:
    changed = copy.deepcopy(document)
    change(changed)
    rejects(name, lambda: builder.row_text_expectations(changed, binding["instructionOccurrences"]), message)

# String subclasses must be normalized at the parser boundary, never by
# weakening strict type equality for source quantities, booleans or containers.
smart = html.fromstring("<p>same</p>").xpath("string()")
assert isinstance(smart, str) and type(smart) is not str
rejects("strict-smart-string-type-check-retained", lambda: _equal(smart, "same", "/fixture"), "type differs")
rejects("strict-bool-versus-integer-check-retained", lambda: _equal(True, 1, "/fixture"), "type differs")

outputs = builder.build()
published = builder.serialized_source_outputs(outputs, ROOT)
for name, data in published.items():
    assert (HERE / "generated" / (name + ".json")).read_bytes() == data, "CSM generated bytes changed: " + name
checks.append("real-csm-build-is-byte-identical")

wrong = copy.deepcopy(document)
wrong["rows"][0]["expectedRowTextSha256"] = "0" * 64
original_read = builder.read
with patch.object(builder, "read", side_effect=lambda path: wrong if Path(path).name == "presentation-row-text-fingerprints.json" else original_read(path)):
    rejects("real-build-rejects-wrong-row-fingerprint", builder.build, "Weapon source occurrence changed")

# The original capture stays untouched. A copied fixture proves that even a
# semantically harmless byte change is rejected by the whole-file SHA guard.
artifact = next(item for item in builder.read(HERE / "sources/enrollment.json")["artifacts"] if item["path"].endswith(".html"))
scratch = Path(os.environ.get("QA_TMP_ROOT", ROOT.parent / "qa-tmp")).resolve()
assert scratch != ROOT and ROOT not in scratch.parents
scratch.mkdir(parents=True, exist_ok=True)
with tempfile.TemporaryDirectory(prefix="parser-source-integrity-", dir=scratch) as temporary:
    target = Path(temporary) / "source.fixture"
    data = (ROOT / artifact["path"]).read_bytes()
    target.write_bytes(data)
    enrollment = {"artifacts": [{**artifact, "path": target.name}]}
    builder.verify_sources(Path(temporary), enrollment)
    target.write_bytes(data + b"\n")
    rejects("whole-source-sha-rejects-one-added-byte", lambda: builder.verify_sources(Path(temporary), enrollment), "Enrolled source hash mismatch")

print(json.dumps({"status": "PASS", "controls": checks, "rows": 70,
                  "generatedOutputs": len(published), "LXML_VERSION": etree.LXML_VERSION,
                  "LIBXML_VERSION": etree.LIBXML_VERSION}))
